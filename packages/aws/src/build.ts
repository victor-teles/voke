import { createBuildPlan, handlerModule } from "@voke/build";
import { createHandlerExportName, functionRegistryEntries } from "voke";
import type { BuildPlan, ProviderBuildInput } from "voke";

import { isDurableFunction } from "./durable";

/** Where `voke build` writes the generated Lambda entry module, relative to the project. */
export const generatedLambdaEntry = ".voke/build/index.ts";
const generatedEntryDirectory = ".voke/build";
const manifestFileName = "voke-manifest.json";

const normalize = (path: string): string =>
  path.replace(/^\.\//u, "").replace(/\/+$/u, "");

/** The entrypoint as imported from the generated module's directory. */
const importPathFromGeneratedEntry = (entrypoint: string): string => {
  if (entrypoint.startsWith("/")) {
    return entrypoint;
  }

  const depth = generatedEntryDirectory.split("/").length;

  return `${"../".repeat(depth)}${normalize(entrypoint)}`;
};

// With a config file, the deployed handlers compose the Gateway from it, so its Plugins apply.
const generatedEntrySource = (
  entrypoint: string,
  exportNames: readonly string[],
  configPath: string | undefined
): string =>
  [
    "// Generated by voke build. Do not edit.",
    `import * as project from ${JSON.stringify(importPathFromGeneratedEntry(entrypoint))};`,
    ...(configPath === undefined
      ? []
      : [
          `import config from ${JSON.stringify(importPathFromGeneratedEntry(configPath))};`,
        ]),
    'import { createLambdaHandlers } from "@voke/aws";',
    "",
    configPath === undefined
      ? "const handlers = createLambdaHandlers(project);"
      : "const handlers = createLambdaHandlers(project, { config });",
    "",
    ...exportNames.map(
      (name) => `export const ${name} = handlers[${JSON.stringify(name)}];`
    ),
    "",
  ].join("\n");

const durableTestingPackage = "@aws/durable-execution-sdk-js-testing";
const durableSdkPackage = "@aws/durable-execution-sdk-js";

/**
 * `build.external` plus the durable packages a Lambda never needs: the testing package (local
 * runs only) always, and the durable SDK when no Function is durable. Both are loaded with
 * `import()` only on the paths that use them, so leaving them out never breaks a handler.
 */
const lambdaExternals = (input: ProviderBuildInput): string[] => {
  const hasDurableFunction = functionRegistryEntries(input.functions).some(
    ([, definition]) => isDurableFunction(definition)
  );

  return [
    ...input.build.external,
    durableTestingPackage,
    ...(hasDurableFunction ? [] : [durableSdkPackage]),
  ];
};

/**
 * The AWS build plan: one generated entry module that exports a Lambda handler per Function, bundled
 * to `<outdir>/index.js`, plus `<outdir>/voke-manifest.json` mapping each Function to its handler.
 * Functions with an explicit `synthesis.entrypoint` keep their own bundle entry and handler.
 */
export const createAwsBuildPlan = (input: ProviderBuildInput): BuildPlan => {
  const generatedFunctions = functionRegistryEntries(input.functions).filter(
    ([, definition]) => definition.synthesis?.entrypoint === undefined
  );
  // Sorted so the generated module does not change when Functions are reordered in code.
  const exportNames = generatedFunctions
    .map(([key]) => createHandlerExportName(key))
    .toSorted();
  const base = createBuildPlan({
    build: { ...input.build, external: lambdaExternals(input) },
    entrypoints: [generatedLambdaEntry],
    functions: input.functions,
    sources: {
      [generatedLambdaEntry]: generatedEntrySource(
        input.entrypoint,
        exportNames,
        input.configPath
      ),
    },
  });
  const entryFile = base.outputs[generatedLambdaEntry]?.file ?? "";
  // "index" when the generated entry is the only bundle; a nested path such as
  // ".voke/build/index" when explicit per-Function entrypoints widen the bundle root.
  const entryModule = handlerModule(entryFile, input.build.outdir);
  const manifest = {
    functions: {
      ...Object.fromEntries(
        generatedFunctions.map(([key]) => [
          key,
          {
            file: entryFile,
            handler: `${entryModule}.${createHandlerExportName(key)}`,
          },
        ])
      ),
      ...base.manifest.functions,
    },
  };

  return {
    ...base,
    files: {
      ...base.files,
      [`${normalize(input.build.outdir)}/${manifestFileName}`]: `${JSON.stringify(manifest, null, 2)}\n`,
    },
    manifest,
  };
};
