import { expect, test } from "bun:test";

import { createFunctions, defineConfig, fn, http, route } from "voke";
import type { StandardSchemaV1 } from "voke";

import { aws, durable, sqs } from "../src/index";

const schema = <TValue>(): StandardSchemaV1<TValue, TValue> => ({
  "~standard": {
    validate: (value) => ({ value }),
    vendor: "voke-test",
    version: 1,
  },
});

const functions = createFunctions({
  http: http({ routes: [route.get("/health", { handler: () => "ok" })] }),
  "process-order": sqs({
    handler: (batch) => batch.ok(),
    message: schema<{ id: string }>(),
    queue: "ordersQueue",
  }),
  report: fn({
    handler: () => "done",
    output: schema<string>(),
    synthesis: { entrypoint: "./src/report.ts" },
  }),
});

const plan = () => {
  const provider = aws();
  const config = defineConfig({ name: "shop", provider });

  return provider.build?.plan?.({
    build: config.build,
    config,
    entrypoint: "./src/index.ts",
    functions,
  });
};

test("generates one Lambda entry module that exports a handler per Function", () => {
  const source = plan()?.sources[".voke/build/index.ts"];

  expect(source).toBe(
    [
      "// Generated by voke build. Do not edit.",
      'import * as project from "../../src/index.ts";',
      'import { createLambdaHandlers } from "@voke/aws";',
      "",
      "const handlers = createLambdaHandlers(project);",
      "",
      'export const http = handlers["http"];',
      'export const processOrder = handlers["processOrder"];',
      "",
    ].join("\n")
  );
});

test("bundles the generated entry and writes a manifest of every Function handler", () => {
  const result = plan();

  expect(result?.entrypoints).toEqual([
    ".voke/build/index.ts",
    "./src/report.ts",
  ]);
  expect(result?.manifest.functions).toEqual({
    http: {
      file: "dist/.voke/build/index.js",
      handler: ".voke/build/index.http",
    },
    "process-order": {
      file: "dist/.voke/build/index.js",
      handler: ".voke/build/index.processOrder",
    },
    report: { file: "dist/src/report.js", handler: "src/report.handler" },
  });
  expect(JSON.parse(result?.files["dist/voke-manifest.json"] ?? "{}")).toEqual(
    result?.manifest
  );
  expect(result?.files["dist/package.json"]).toBe('{"type":"module"}\n');
});

test("a project without explicit entrypoints bundles to <outdir>/index.js", () => {
  const provider = aws();
  const config = defineConfig({ name: "shop", provider });
  const result = provider.build?.plan?.({
    build: config.build,
    config,
    entrypoint: "./src/index.ts",
    functions: createFunctions({
      http: http({ routes: [route.get("/", { handler: () => "ok" })] }),
    }),
  });

  expect(result?.outputs).toEqual({
    ".voke/build/index.ts": { file: "dist/index.js" },
  });
  expect(result?.manifest.functions).toEqual({
    http: { file: "dist/index.js", handler: "index.http" },
  });
});

const externalsOf = (command: readonly string[] | undefined): string[] =>
  (command ?? []).flatMap((part, index, all) =>
    all[index - 1] === "--external" ? [part] : []
  );

test("the durable testing package is never bundled, and the durable SDK is bundled only when a Function needs it", () => {
  const provider = aws();
  const config = defineConfig({ name: "shop", provider });
  const withDurable = provider.build?.plan?.({
    build: config.build,
    config,
    entrypoint: "./src/index.ts",
    functions: createFunctions({
      fulfil: durable({
        executionTimeout: { hours: 1 },
        handler: () => "done",
        output: schema<string>(),
      }),
    }),
  });

  expect(externalsOf(withDurable?.command)).toEqual([
    "@aws-sdk/*",
    "@aws/durable-execution-sdk-js-testing",
  ]);
  expect(externalsOf(plan()?.command)).toEqual([
    "@aws-sdk/*",
    "@aws/durable-execution-sdk-js-testing",
    "@aws/durable-execution-sdk-js",
  ]);
});
